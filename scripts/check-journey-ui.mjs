/** Node-only markup checks. Does not claim WebGL rendering or browser playtest. */
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const oldDocument = globalThis.document;
globalThis.document = { hidden: false };
const vite = await createServer({ configFile: false, root: process.cwd(), server: { middlewareMode: true, hmr: false }, esbuild: { jsx: 'automatic' } });
let assertions = 0;
const check = (value, message) => { assert.ok(value, message); assertions++; };
const disabled = (markup, text) => {
 const index = markup.indexOf(text); assert.ok(index >= 0, `Missing control: ${text}`);
 const start = markup.lastIndexOf('<button', index); return markup.slice(start, markup.indexOf('>', start)).includes('disabled');
};
try {
 const { JourneyOperations } = await vite.ssrLoadModule('/client/src/ui/JourneyOperations.tsx');
 const { ImpostorKit, SecurityInteractions, nearestToolTarget } = await vite.ssrLoadModule('/client/src/ui/CabinSecurity.tsx');
 const { FlightGame } = await vite.ssrLoadModule('/server/src/systems/game.ts');
 const { BOARDING_DOCUMENTS, BOARDING_ENTRANCE } = await vite.ssrLoadModule('/shared/protocol.ts');
 const game = new FlightGame('1234', true, () => {});
 game.addPlayer('captain', 'Avery');
 const base = game.snapshot(); base.phase = 'playing'; base.training = false; base.players[0].role = 'Captain';
 const render = (snapshot, options = {}) => renderToStaticMarkup(createElement(JourneyOperations, { snapshot, me: snapshot.players[0], ...options }));
 const scenario = () => structuredClone(base);
 let s = scenario(); let html = render(s);
 check(html.includes('Receive your briefing.'), 'Captain sees crew documents');
 check(disabled(html, 'Collect documents'), 'Document checklist initially prevents claiming before review');
 s.players[0].role = 'Passenger'; html = render(s);
 check(html.includes('Your boarding pass.'), 'Passenger sees own boarding pass');
 check(!html.includes('Crew manifest received'), 'Passenger does not get crew paperwork');
 s = scenario(); Object.assign(s.players[0], { x: BOARDING_DOCUMENTS.x, z: BOARDING_DOCUMENTS.z }); html = render(s);
 check((html.match(/type="checkbox"/g) ?? []).length === 3, 'Crew reviews three dispatch items');
 check(!/<input[^>]*type="checkbox"[^>]*disabled/.test(html), 'Desk proximity unlocks review');
 s.players[0].x += BOARDING_DOCUMENTS.radius + .01; html = render(s);
 check(/<input[^>]*type="checkbox"[^>]*disabled/.test(html), 'Review disables outside exact server desk radius');
 s = scenario(); s.operations.roster[0].documentsReceived = true; Object.assign(s.players[0], { x: BOARDING_ENTRANCE.x, z: BOARDING_ENTRANCE.z }); html = render(s);
 check(!disabled(html, 'Scan pass &amp; board'), 'Exact gate proximity enables scanning');
 s.players[0].x += BOARDING_ENTRANCE.radius + .01; html = render(s);
 check(disabled(html, 'Scan pass &amp; board'), 'Server gate radius respected by button');
 s = scenario(); s.operations.roster[0].boarded = true; html = render(s);
 check(disabled(html, 'Begin takeoff'), 'Takeoff locked before departure checks and cockpit access');
 for (const objective of s.story.objectives) objective.current = objective.target;
 for (const npc of s.npcs) if (npc.kind === 'passenger') Object.assign(npc, { needsSeat: false, pose: 'seated' });
 Object.assign(s.players[0], { x: .65, z: -11.6 }); html = render(s);
 check(!disabled(html, 'Begin takeoff'), 'Captain can depart with completed checks at controls');
 s.operations.bomb = { x: 0, z: 0, remaining: 60, disarmProgress: 0 }; html = render(s);
 check(disabled(html, 'Begin takeoff'), 'Active device prevents takeoff');
 s = scenario(); s.operations.stage = 'takeoff'; html = render(s);
 check(html.includes('aria-label="Engine thrust"'), 'Captain gets real flight controls');
 check(html.includes('135 kt') && html.includes('600 ft'), 'Hints match authoritative takeoff thresholds');
 s.players[0].role = 'Passenger'; html = render(s);
 check(!html.includes('aria-label="Engine thrust"'), 'Passenger cannot operate pilot controls');
 s.players[0].role = 'First Officer'; html = render(s);
 check(!html.includes('aria-label="Engine thrust"'), 'First Officer cannot operate Captain controls');
 s.training = true; html = render(s);
 check(html.includes('aria-label="Engine thrust"'), 'Training permits controls');
 s = scenario(); s.operations.stage = 'takeoff'; s.players[0].detained = true; html = render(s);
 check(/aria-label="Engine thrust"[^>]*disabled/.test(html), 'Detained pilot inputs disabled');
 s.players[0].detained = false; s.operations.restraints.captain = 20; html = render(s);
 check(/aria-label="Engine thrust"[^>]*disabled/.test(html), 'Restrained pilot inputs disabled');
 s = scenario(); s.operations.stage = 'cruise'; html = render(s);
 check(html === '', 'No premature permanent approach panel during cruise');
 s.operations.landingReady = true; html = render(s);
 check(disabled(html, 'Begin approach'), 'Approach locked away from cockpit');
 Object.assign(s.players[0], { x: .65, z: -11.6 }); html = render(s);
 check(!disabled(html, 'Begin approach'), 'Approach allowed at cockpit after clearance');
 s.operations.stage = 'landing'; html = render(s);
 check(html.includes('110–150 kt'), 'Landing hint matches stable target band');
 s.phase = 'ended'; s.operations.stage = 'crashed'; check(render(s) === '', 'Root owns crash/debrief overlay without duplicate panel');
 s.phase = 'lobby'; check(render(s) === '', 'Root owns lobby UI');
 s = scenario(); s.operations.stage = 'cruise'; s.operations.roster[0].boarded = true;
 const kit = (secret) => renderToStaticMarkup(createElement(ImpostorKit, { snapshot: s, me: s.players[0], secret }));
 const privateKit = { allegiance: 'saboteur', inventory: ['knife', 'rope', 'bomb'], cooldown: 0, killCooldown: 0, objectives: [], teammates: [] };
 check(kit({ ...privateKit, allegiance: 'crew', inventory: [] }) === '', 'Ordinary crew never see private inventory controls');
 check(['Knife', 'Rope', 'Sabotage case', 'Oxygen cut'].every(label => kit(privateKit).includes(label)), 'Private kit presents all available fictional tools');
 Object.assign(s.players[0], { x: 0, z: 5, equippedTool: 'rope' });
 s.npcs = [{ ...s.npcs[0], id: 'nearby-npc', alive: true, x: 0, z: 5.1 }];
 s.players.push({ ...s.players[0], id: 'other', x: 0, z: 5.5 });
 s.operations.roster.push({ playerId: 'other', documentsReceived: true, boarded: false });
 check(!nearestToolTarget(s, s.players[0]), 'Rope does not offer NPCs or unboarded players');
 s.operations.roster[1].boarded = true;
 check(nearestToolTarget(s, s.players[0])?.id === 'other', 'Rope offers a nearby boarded player');
 s.operations.restraints.other = 20;
 check(!nearestToolTarget(s, s.players[0]), 'Already restrained player cannot be offered again');
 s.players[0].equippedTool = 'knife';
 check(nearestToolTarget(s, s.players[0])?.id === 'nearby-npc', 'Knife can target a living nearby cabin NPC');
 s.experience.players.captain.incapacitated = true;
 check(disabled(kit(privateKit), 'Conceal <kbd>'), 'Incapacitated impostor cannot use private controls');
 s.experience.players.captain.incapacitated = false; s.players[0].equippedTool = null; s.players[0].role = 'Engineer';
 s.operations.bomb = { x: 0, z: 5.5, remaining: 42, disarmProgress: .5 };
 const security = () => renderToStaticMarkup(createElement(SecurityInteractions, { snapshot: s, me: s.players[0] }));
 check(security().includes('HOLD TO HELP'), 'Nearby Engineer receives physical disarm control');
 s.players[0].role = 'Passenger';
 check(!security().includes('HOLD TO HELP') && security().includes('42s'), 'Passenger sees alert without inheriting disarm authority');
 s.players[0].role = 'Engineer'; s.operations.bomb.z = 7.1;
 check(!security().includes('HOLD TO HELP'), 'Disarm prompt matches exact two-metre server range');
 s.operations.bomb = null; s.players[0].role = 'Cabin Crew';
 check(security().includes('Release'), 'Cabin Crew receives nearby restraint rescue control');
 console.log(`Journey UI: ${assertions} server-rendered markup assertions passed. WebGL appearance and held-event behavior require a browser playtest.`);
} finally { await vite.close(); if (oldDocument === undefined) delete globalThis.document; else globalThis.document = oldDocument; }
